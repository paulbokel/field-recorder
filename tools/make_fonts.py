#!/usr/bin/env python3
"""Generate Adafruit-GFX bitmap fonts (Literata + Geist Mono) for the Field Recorder UI.

  pip install pillow
  put Literata-Regular.ttf and GeistMono-Regular.ttf in tools/ttf/  (Google Fonts, static instances)
  python tools/make_fonts.py

Writes src/fonts/*.h and src/fonts/ui_fonts.h; the firmware picks them up automatically.
Order of FONTS must match FontId in src/app.h.
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, 'ttf')
OUT = os.path.join(HERE, '..', 'src', 'fonts')
SERIF, MONO = 'Literata-Regular.ttf', 'GeistMono-Regular.ttf'
LATIN, ASCII, DIGITS = (0x20, 0xFF), (0x20, 0x7E), (0x20, 0x3A)

FONTS = [  # name, file, px size, code range
    ('SerifXL', SERIF, 66, ASCII), ('SerifL', SERIF, 42, LATIN), ('SerifM', SERIF, 28, LATIN), ('SerifS', SERIF, 23, LATIN),
    ('MonoXXL', MONO, 112, DIGITS), ('MonoXL', MONO, 88, ASCII), ('MonoL', MONO, 44, LATIN),
    ('MonoM', MONO, 17, LATIN), ('MonoS', MONO, 14, LATIN),
]
SPECIAL = {0x7F: '\u2026', 0x80: '\u203A', 0x83: '\u2014', 0x84: '\u2013', 0x87: '\u2192', 0x88: '\u2191', 0x89: '\u2193'}
SHAPES = {0x81: 'up', 0x82: 'down', 0x85: 'dot', 0x86: 'play'}   # drawn, so they exist in every font


def shape(kind, cap):
    s = max(6, int(cap * 0.8))
    img = Image.new('L', (s, s), 0); d = ImageDraw.Draw(img)
    if kind == 'up': d.polygon([(0, s - 1), (s - 1, s - 1), (s // 2, 0)], fill=255)
    elif kind == 'down': d.polygon([(0, 0), (s - 1, 0), (s // 2, s - 1)], fill=255)
    elif kind == 'play': d.polygon([(0, 0), (0, s - 1), (s - 1, s // 2)], fill=255)
    else: d.ellipse([0, 0, s - 1, s - 1], fill=255)
    return img, 0, -s, s + max(2, s // 4)


def build(name, path, size, rng):
    font = ImageFont.truetype(path, size)
    try:   # variable fonts from google/fonts: regular weight, optical size matched to px like the browser does
        axes = {a['name'].decode() if isinstance(a['name'], bytes) else a['name']: a for a in font.get_variation_axes()}
        vals = []
        for n, a in axes.items():
            if n.lower().startswith('weight'): vals.append(400)
            elif n.lower().startswith('optical'): vals.append(max(a['minimum'], min(a['maximum'], size * 0.75)))
            else: vals.append(a['default'])
        font.set_variation_by_axes(vals)
    except Exception:
        pass
    asc, desc = font.getmetrics()
    cap = -font.getbbox('H', anchor='ls')[1]
    thr = 110 if size < 20 else 128
    data, glyphs = bytearray(), []
    for code in range(rng[0], rng[1] + 1):
        off = len(data)
        if code in SHAPES:
            img, xo, yo, adv = shape(SHAPES[code], cap)
        elif (0x7F <= code <= 0xA0 and code not in SPECIAL) or code == 0x20:
            glyphs.append((off, 0, 0, round(font.getlength(' ')), 0, 0)); continue
        else:
            ch = SPECIAL.get(code, chr(code))
            l, t, r, b = font.getbbox(ch, anchor='ls')
            adv = round(font.getlength(ch))
            if r <= l or b <= t:
                glyphs.append((off, 0, 0, adv, 0, 0)); continue
            img = Image.new('L', (r - l, b - t), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor='ls')
            xo, yo = l, t
        w, h = img.size; px = img.load(); bits = 0; n = 0
        for y in range(h):
            for x in range(w):
                bits = (bits << 1) | (1 if px[x, y] >= thr else 0); n += 1
                if n == 8: data.append(bits); bits = n = 0
        if n: data.append(bits << (8 - n))
        glyphs.append((off, w, h, adv, xo, yo))
    assert len(data) < 65536, f'{name}: bitmap too large, reduce size or range'
    lines = [f'// {os.path.basename(path)} {size}px, generated by tools/make_fonts.py', '#pragma once',
             f'const uint8_t {name}Bitmaps[] PROGMEM = {{']
    for i in range(0, len(data), 24): lines.append('  ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 24]) + ',')
    lines.append('};'); lines.append(f'const GFXglyph {name}Glyphs[] PROGMEM = {{')
    for g in glyphs:
        o, w, h, a, xo, yo = g
        assert w < 256 and h < 256 and a < 256 and -128 <= xo < 128 and -128 <= yo < 128, f'{name}: glyph out of range'
        lines.append(f'  {{ {o}, {w}, {h}, {a}, {xo}, {yo} }},')
    lines.append('};')
    lines.append(f'const GFXfont {name} PROGMEM = {{ (uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, 0x{rng[0]:02X}, 0x{rng[1]:02X}, {asc + desc} }};')
    with open(os.path.join(OUT, name + '.h'), 'w') as f: f.write('\n'.join(lines) + '\n')
    print(f'{name}: {len(data)} bytes')


os.makedirs(OUT, exist_ok=True)
for name, file, size, rng in FONTS: build(name, os.path.join(TTF, file), size, rng)
with open(os.path.join(OUT, 'ui_fonts.h'), 'w') as f:
    f.write('#pragma once\n#define UI_FONTS_LATIN1 1\n')
    for name, *_ in FONTS: f.write(f'#include "{name}.h"\n')
    f.write('static const UIFont UI_FONTS[F_COUNT] = {\n' + ''.join(f'  {{&{n}, 1}},\n' for n, *_ in FONTS) + '};\n')
print('done → src/fonts/ui_fonts.h')
